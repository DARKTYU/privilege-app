// Generate table DTOs from schema.sql and the activity tracking migration.
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const sqlFiles = ['schema.sql', 'activity_tracking.sql'].map(file =>
  fs.readFileSync(path.join(root, 'supabase', file), 'utf8'));
const tableBodies = new Map();
for (const sql of sqlFiles) {
  for (const [, table, body] of sql.matchAll(
    /create table if not exists public\.(\w+) \(([\s\S]*?)\n\);/g,
  )) {
    if (!tableBodies.has(table)) tableBodies.set(table, body);
  }
}
for (const [, table, body] of sqlFiles[1].matchAll(
  /alter table public\.(\w+)([\s\S]*?);/gi,
)) {
  const columns = [...body.matchAll(
    /add column if not exists\s+(\w+)\s+(uuid|text|integer|boolean|numeric(?:\(\d+,\d+\))?|timestamptz|date|jsonb)(?=\s|,|$)/gi,
  )];
  if (!tableBodies.has(table)) continue;
  for (let i = 0; i < columns.length; i++) {
    const column = columns[i];
    const end = columns[i + 1]?.index ?? body.length;
    const suffix = body.slice(column.index + column[0].length, end);
    tableBodies.set(
      table,
      `${tableBodies.get(table)},\n ${column[1]} ${column[2]}${/\bnot null\b/i.test(suffix) ? ' not null' : ''}`,
    );
  }
}
if (!tableBodies.size) throw new Error('No table declarations found');

const camel = name => name.replace(/_([a-z])/g, (_, c) => c.toUpperCase());
const nameFor = name => {
  const special = {xp_points: 'xp_point', split_day_exercises: 'split_day_exercise', plan_day_exercises: 'plan_day_exercise'};
  const singular = special[name] || (name.endsWith('s') ? name.slice(0, -1) : name);
  return singular.split('_').map(s => s[0].toUpperCase() + s.slice(1)).join('') + 'Row';
};
const typeFor = kind => {
  if (kind === 'integer') return 'int';
  if (kind === 'boolean') return 'bool';
  if (kind.startsWith('numeric')) return 'double';
  if (kind === 'date' || kind === 'timestamptz') return 'DateTime';
  if (kind === 'jsonb') return 'Map<String, dynamic>';
  return 'String';
};
const decode = (name, kind, nullable) => {
  const v = `json['${name}']`;
  let value = `${v} as String`;
  if (kind === 'boolean') value = `${v} as bool`;
  else if (kind === 'integer') value = `(${v} as num).toInt()`;
  else if (kind.startsWith('numeric')) value = `(${v} as num).toDouble()`;
  else if (kind === 'date' || kind === 'timestamptz') value = `DateTime.parse(${v} as String)`;
  else if (kind === 'jsonb') value = `Map<String, dynamic>.from(${v} as Map)`;
  return nullable ? `${v} == null ? null : ${value}` : value;
};
const encode = (name, kind, nullable) => {
  const v = camel(name);
  if (kind === 'date') return nullable ? `${v} == null ? null : _dateOnly(${v}!)` : `_dateOnly(${v})`;
  if (kind === 'timestamptz') return `${v}${nullable ? '?' : ''}.toIso8601String()`;
  return v;
};
const lines = [
  '// Generated by scripts/generate_supabase_models.js. Do not edit by hand.',
  '// Row DTOs represent complete database rows; omit server-owned columns on writes.',
  '',
  'String _dateOnly(DateTime value) =>',
  "    '${value.year.toString().padLeft(4, '0')}-'",
  "    '${value.month.toString().padLeft(2, '0')}-'",
  "    '${value.day.toString().padLeft(2, '0')}';",
  '',
];
for (const [table, body] of tableBodies) {
  const parts = body.split(/,\s*(?![^()]*\))/);
  const columns = parts.flatMap(part => {
    const m = part.match(/^\s*(\w+)\s+(uuid|text|integer|boolean|numeric(?:\(\d+,\d+\))?|timestamptz|date|jsonb|public\.\w+)(?=\s|$)([\s\S]*)/);
    if (!m) return [];
    return [{name: m[1], kind: m[2], nullable: !/\bnot null\b|\bprimary key\b/.test(m[3])}];
  });
  if (!columns.length) throw new Error(`No fields found for ${table}`);
  const name = nameFor(table);
  lines.push(`class ${name} {`, `  const ${name}({`);
  for (const c of columns) lines.push(`    ${c.nullable ? '' : 'required '}this.${camel(c.name)},`);
  lines.push('  });', '');
  for (const c of columns) lines.push(`  final ${typeFor(c.kind)}${c.nullable ? '?' : ''} ${camel(c.name)};`);
  lines.push('', `  factory ${name}.fromJson(Map<String, dynamic> json) => ${name}(`);
  for (const c of columns) lines.push(`        ${camel(c.name)}: ${decode(c.name, c.kind, c.nullable)},`);
  lines.push('      );', '', '  Map<String, dynamic> toJson() => {');
  for (const c of columns) lines.push(`        '${c.name}': ${encode(c.name, c.kind, c.nullable)},`);
  lines.push('      };', '}', '');
}
const destination = path.join(root, 'lib', 'models', 'supabase_rows.dart');
fs.mkdirSync(path.dirname(destination), {recursive: true});
fs.writeFileSync(destination, lines.join('\n'));
console.log(`Generated ${tableBodies.size} table models in ${destination}`);
